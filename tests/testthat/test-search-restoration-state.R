library(testthat)
test_that('retiring a captured owner is idempotent and cannot retire its replacement', {
    f <- ownership_harness(FALSE); on.exit(f$close(),add=TRUE)
    a <- f$e$begin_search_run('orthologous','query-A')
    settle <- f$e$start_search_child('orthologous',a$id)
    expect_true(f$e$stateHelpersDomain$retire_search_owner('orthologous',a$id))
    expect_identical(f$state('orthologous')$status,'cancelled')
    expect_false(f$e$stateHelpersDomain$retire_search_owner('orthologous',a$id))
    b <- f$e$begin_search_run('orthologous','query-A'); expect_true(b$ok)
    before <- f$state('orthologous')
    expect_false(f$e$stateHelpersDomain$retire_search_owner('orthologous',a$id))
    settle(); settle(); expect_identical(f$state('orthologous'),before)
})
test_that('work retirement revokes terminal continuations without changing ordinary cancellation', {
    f <- ownership_harness(FALSE); on.exit(f$close(),add=TRUE)
    a <- f$e$begin_search_run('homologous','query-A')
    f$e$release_search_admission('homologous',a$id)
    expect_false(f$e$cancel_search_operation('homologous',a$id))
    expect_true(f$e$owns_search_run('homologous',a$id,terminal=TRUE))
    expect_true(f$e$stateHelpersDomain$retire_search_owner('homologous',a$id))
    expect_identical(f$state('homologous')$status,'completed')
    expect_false(f$e$owns_search_run('homologous',a$id,terminal=TRUE))
    expect_true(f$e$begin_search_run('homologous','query-A')$ok)
})
test_that('view guard suppresses stale publication and runs cleanup through teardown', {
    f <- ownership_harness(FALSE); on.exit(f$close(),add=TRUE)
    wrote <- cleaned <- 0L
    late <- f$e$work_view_guard(function() wrote <<- wrote+1L,cleanup=function()cleaned<<-cleaned+1L)
    f$e$invalidate_search_preparation('orthologous')
    late(); expect_identical(wrote,1L); expect_identical(cleaned,1L)
    f$e$invalidate_search_preparation('homologous')
    wrote <- 0L
    late(); expect_identical(wrote,0L); expect_identical(cleaned,2L)
    f$close()
    f$e$searchPreparationTokenHomo <- f$e$searchPreparationTokenOrtho <- function(...)stop('destroyed reactive')
    late(); expect_identical(cleaned,3L)
    closed <- f$e$work_view_guard(function()stop('late publication'),cleanup=function()cleaned<<-cleaned+1L)
    expect_no_error(closed()); expect_identical(cleaned,4L)
})
